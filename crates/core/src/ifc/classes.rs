//! IFC4's element classes, as a component may be written as one: what follows each one's `Tag`, its type object's attributes
//! after its `ElementType` (where IFC4 has a `<CLASS>TYPE` that isn't abstract) and the predefined types it takes. Read from
//! the IFC4 ADD2 TC1 schema (ISO 16739-1:2018) by `ci/ifc4_classes.py`, which prints the table; every IfcElement but the
//! abstract ones, the features (openings, projections, surface features) and the virtual element.

/// A class: its name as STEP writes it; its attributes after `Tag`, comma-separated, `P` where its predefined type goes, `$`
/// one left unset, `*` a derived one and `.NOTDEFINED.` a required enumeration; its type object's attributes after its
/// `ElementType` the same way, where it has one; and its predefined types, space-separated.
pub type Class = (&'static str, &'static str, Option<&'static str>, &'static str);

/// A class of IFC4, by its name as STEP writes it (`IFCPLATE`).
pub fn class(name: &str) -> Option<&'static Class> {
    CLASSES.binary_search_by(|c| c.0.cmp(name)).ok().and_then(|i| CLASSES.get(i))
}

/// Whether `class` takes `predefined` (as a file spells it, without the dots) as its predefined type.
pub fn takes(class: &Class, predefined: &str) -> bool {
    class.3.split(' ').any(|k| k == predefined)
}

/// `attributes` (as [`Class`] holds them) written, each with its comma ahead of it, `P` as `predefined`.
pub fn fill(attributes: &str, predefined: &str) -> String {
    attributes.split(',').filter(|a| !a.is_empty()).map(|a| format!(",{}", if a == "P" { predefined } else { a })).collect()
}

/// `attributes` (as [`Class`] holds them) written in two, each with its comma ahead of it: those ahead of the predefined type,
/// and those after it (all ahead, for a class that has none).
pub fn around(attributes: &str) -> (String, String) {
    let all: Vec<&str> = attributes.split(',').filter(|a| !a.is_empty()).collect();
    let at = all.iter().position(|a| *a == "P").unwrap_or(all.len());
    let (before, after) = all.split_at(at);
    (fill(&before.join(","), ""), fill(&after.iter().skip(1).copied().collect::<Vec<_>>().join(","), ""))
}

/// Where among a product's attributes (from 0) `attributes`, as [`Class`] holds them, put its predefined type, the first of
/// them being attribute `first`.
pub fn predefined_at(attributes: &str, first: usize) -> Option<usize> {
    attributes.split(',').position(|a| a == "P").map(|i| first + i)
}


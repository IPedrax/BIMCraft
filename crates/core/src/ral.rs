/// A colour of the RAL Classic collection.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Ral {
    /// Its four digits.
    pub code: u16,
    /// Its English name.
    pub name: &'static str,
    /// CIELAB, under the D50 illuminant.
    pub lab: [f64; 3],
}

impl Ral {
    /// The nearest sRGB colour: CIELAB under D50 to XYZ, adapted to sRGB's white (Bradford), what is out of its gamut clipped.
    pub fn rgb(&self) -> [u8; 3] {
        let [l, a, b] = self.lab;
        let fy = (l + 16.0) / 116.0;
        let (fx, fz) = (fy + a / 500.0, fy - b / 200.0);
        let f = |t: f64| if t > 6.0 / 29.0 { t * t * t } else { 3.0 * (6.0f64 / 29.0).powi(2) * (t - 4.0 / 29.0) };
        let (x, y, z) = (0.96422 * f(fx), f(fy), 0.82521 * f(fz));
        [
            3.1338561 * x - 1.6168667 * y - 0.4906146 * z,
            -0.9787684 * x + 1.9161415 * y + 0.0334540 * z,
            0.0719453 * x - 0.2289914 * y + 1.4052427 * z,
        ]
        .map(|c| {
            let c = c.clamp(0.0, 1.0);
            let gamma = if c <= 0.0031308 { 12.92 * c } else { 1.055 * c.powf(1.0 / 2.4) - 0.055 };
            (gamma * 255.0).round() as u8
        })
    }
}

